qdrop("two sides quoted at DIFFERENT lines (not a real pair)", lambda k, v: v["Over"][1] != v["Under"][1])
qdrop("no box row for that player-game (DNP / not on the sheet)", lambda k, v: (k[0], k[2]) not in pgrow)
qdrop("player logged <8 minutes (DNP-adjacent; outcome is noise)", lambda k, v: pgrow[(k[0], k[2])]["min"] < 8)
qdrop("actual exactly equals the line (PUSH -> ungradable)", lambda k, v: pgrow[(k[0], k[2])][k[1]] == v["Over"][1])
histp = collections.defaultdict(list)
