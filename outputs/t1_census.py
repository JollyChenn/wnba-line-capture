def badp(r):
    a, b = r["prices"].split(",")
    return f(a) is None or f(b) is None
d2("non-numeric american price", badp)
def am(p):
    v = f(p)
    return None if v is None else ((-v)/((-v)+100) if v < 0 else 100/(v+100))
def extreme(r):
    a, b = r["prices"].split(",")
    pa, pb = am(a), am(b)
    return (pa is not None and (pa < 1/15.0 or pa > 1/1.02)) or (pb is not None and (pb < 1/15.0 or pb > 1/1.02))
