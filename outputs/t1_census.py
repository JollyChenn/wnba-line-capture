def d2(name, pred):
    global c2
    keep = []; gone = 0
    for r in c2:
        if pred(r): gone += 1
        else: keep.append(r)
    lex[name] = gone; c2 = keep
d2("unparseable ts", lambda r: ts(r.get("ts")) is None)
