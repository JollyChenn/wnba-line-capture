P("")
P("Contradictory quotes (same player/market/side/line/instant, more than one price): **%d** keys." % contra)
P("Kept -- they are genuine within-second re-quotes -- but they mean a naive groupby double-counts.")
valid_obs = len(cur)
P("")
P("Valid observations after the ledger: **%s** of %s (%.2f%%)" % (format(valid_obs, ","), format(raw_obs, ","), 100*valid_obs/raw_obs))
P("")

teamof = {}; pgrow = {}
for r in BX:
    gid = r["game_id"]
    if gid not in gmeta: continue
    d, tp, h, a = gmeta[gid]
    pl = (r.get("player") or "").lower()
    p_, rb, as_ = f(r.get("pts")) or 0, f(r.get("reb")) or 0, f(r.get("ast")) or 0
    pgrow[(pl, tp)] = dict(tm=r["team"], min=f(r.get("min")) or 0, gid=gid,
        pts=p_, reb=rb, ast=as_, pra=p_+rb+as_, pr=p_+rb, pa=p_+as_, ra=rb+as_)
    teamof[pl] = r["team"]
tips_of = collections.defaultdict(list)
for gid, (d, tp, h, a) in gmeta.items(): tips_of[h].append(tp); tips_of[a].append(tp)
for v in tips_of.values(): v.sort()
def game_for(tm, when):
    for t in tips_of.get(tm, []):
        if when <= t and (t - when).total_seconds() <= 60*3600: return t
    return None
noplayer = 0; nogame = 0
sidem = collections.defaultdict(dict); tsspan = collections.defaultdict(list)
rawgames = set()
for r in cur:
    pl = (r.get("player") or "").lower(); tm = teamof.get(pl)
    if not tm: noplayer += 1; continue
    t = ts(r["captured_utc"]); g2 = game_for(tm, t)
    if not g2: nogame += 1; continue
    rawgames.add(g2)
    mk = r["market"]; sd = r["side"]; ln = f(r["line"]); o = f(r["odds"])
    d = sidem[(pl, mk, g2)]
    prev = d.get(sd)
    if prev is None or t > prev[0]: d[sd] = (t, ln, o)
    tsspan[(pl, mk, g2)].append((t, sd, ln, o))
P("### 1b. Quote-level census -- collapse to one closing two-sided quote per player-market-game")
P("")
P("- Valid rows whose player string never appears in the 2026 box file (no team -> ungradable): **%s**" % format(noplayer, ","))
P("- Valid rows with no scheduled game inside the 60h forward window (off-day board): **%s**" % format(nogame, ","))
P("- Raw (player, market, game) quote keys: **%s** across **%d** games" % (format(len(sidem), ","), len(rawgames)))
qex = collections.OrderedDict()
q = list(sidem.items())
def qdrop(name, pred):
    global q
    keep = []; gone = 0
    for k, v in q:
        if pred(k, v): gone += 1
        else: keep.append((k, v))
    qex[name] = gone; q = keep
