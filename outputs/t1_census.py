excl = collections.OrderedDict()
def drop(name, rows, pred):
    keep = []; gone = 0
    for r in rows:
        if pred(r): gone += 1
        else: keep.append(r)
    excl[name] = gone
    return keep
cur = BD
cur = drop("unparseable capture timestamp", cur, lambda r: ts(r.get("captured_utc")) is None)
cur = drop("market outside the 7 modelled stats", cur, lambda r: r.get("market") not in ALL_MK)
cur = drop("missing or blank side", cur, lambda r: r.get("side") not in ("Over", "Under"))
cur = drop("missing / non-numeric line", cur, lambda r: f(r.get("line")) is None)
cur = drop("missing / non-numeric odds", cur, lambda r: f(r.get("odds")) is None)
cur = drop("odds <= 1.00 (impossible decimal price)", cur, lambda r: (f(r.get("odds")) or 9) <= 1.0)
cur = drop("extreme odds (>15.0 or <1.02)", cur, lambda r: not (1.02 <= (f(r.get("odds")) or 0) <= 15.0))
cur = drop("line <= 0", cur, lambda r: (f(r.get("line")) or 1) <= 0)
seen = set(); dup = 0; keep = []
for r in cur:
    k = ((r.get("player") or "").lower(), r.get("market"), r.get("side"), f(r.get("line")),
         r.get("captured_utc"), f(r.get("odds")))
    if k in seen: dup += 1
    else: seen.add(k); keep.append(r)
excl["exact duplicate (player,market,side,line,timestamp,odds)"] = dup
cur = keep
