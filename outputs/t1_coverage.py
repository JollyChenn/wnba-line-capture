# ---------- whole-dataset census ----------
def census(name, rows, tcol, gamefn=None, playerfn=None, mkfn=None, book=""):
    tt = [t for t in (ts(r.get(tcol)) for r in rows) if t]
    if not tt: return None
    days = sorted(set(t.date() for t in tt))
    d = dict(name=name, n=len(rows), book=book,
             t0=min(tt).date().isoformat(), t1=max(tt).date().isoformat(),
             span=(max(tt).date() - min(tt).date()).days + 1, dates=len(days))
    d["games"] = len(set(gamefn(r) for r in rows) - {None}) if gamefn else None
    d["players"] = len(set(playerfn(r) for r in rows) - {None, ""}) if playerfn else None
    d["markets"] = len(set(mkfn(r) for r in rows) - {None, ""}) if mkfn else None
    return d

