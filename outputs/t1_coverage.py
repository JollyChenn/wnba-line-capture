# ---------- prop-book intra-game clustering ----------
P("## 3. Intra-game clustering in the prop book (the same section-44 question, pre-game side)")
P("")
teamof = {}; pgrow = {}
for r in BX:
    gid = r["game_id"]
    if gid not in gmeta: continue
    d, tp, h, a = gmeta[gid]
    pl = (r.get("player") or "").lower()
    p_, rb, as_ = f(r.get("pts")) or 0, f(r.get("reb")) or 0, f(r.get("ast")) or 0
    pgrow[(pl, tp)] = dict(tm=r["team"], min=f(r.get("min")) or 0, gid=gid,
        pts=p_, reb=rb, ast=as_, pra=p_+rb+as_, pr=p_+rb, pa=p_+as_, ra=rb+as_)
    teamof[pl] = r["team"]
tips_of = collections.defaultdict(list)
for gid, (d, tp, h, a) in gmeta.items(): tips_of[h].append(tp); tips_of[a].append(tp)
for v in tips_of.values(): v.sort()
def game_for(tm, when):
    for t in tips_of.get(tm, []):
        if when <= t and (t - when).total_seconds() <= 60*3600: return t
    return None
gid_of = {tp: gid for gid, (d, tp, h, a) in gmeta.items()}
sidem = collections.defaultdict(dict)
for r in BD:
    pl = (r.get("player") or "").lower(); tm = teamof.get(pl)
    if not tm or r.get("market") not in ALL_MK or r.get("side") not in ("Over", "Under"): continue
    t = ts(r.get("captured_utc")); ln = f(r.get("line")); o = f(r.get("odds"))
    if t is None or ln is None or o is None: continue
    g2 = game_for(tm, t)
    if not g2: continue
    d = sidem[(pl, r["market"], g2)]
    prev = d.get(r["side"])
    if prev is None or t > prev[0]: d[r["side"]] = (t, ln, o)
Q = []
for (pl, mk, gt), sd in sidem.items():
    if "Over" not in sd or "Under" not in sd: continue
    if sd["Over"][1] != sd["Under"][1]: continue
    row = pgrow.get((pl, gt))
    if not row or row["min"] < 8: continue
    ln = sd["Over"][1]
    if row[mk] == ln: continue
    Q.append(dict(gid=gid_of.get(gt), pl=pl, mk=mk, gt=gt, line=ln,
                  over=1 if row[mk] > ln else 0, oo=sd["Over"][2], uo=sd["Under"][2]))
byg = collections.defaultdict(list)
for r in Q: byg[r["gid"]].append(r)
sizes = [len(v) for v in byg.values()]
P("Gradable two-sided quotes: **%s** across **%d** games (median **%.0f** quotes per game)."
  % (format(len(Q), ","), len(byg), statistics.median(sizes)))
P("")
P("A game is one basketball game: if it runs fast, most of that night's overs cash together. So the")
P("quotes inside a game are not independent. I measure the intraclass correlation of the binary")
P("`over won` outcome using the standard one-way ANOVA estimator, at the game block.")
P("")
grand = statistics.mean(r["over"] for r in Q)
k = len(Q)/len(byg)
msb = sum(len(v)*(statistics.mean(x["over"] for x in v) - grand)**2 for v in byg.values())/(len(byg)-1)
msw = sum(sum((x["over"] - statistics.mean(y["over"] for y in v))**2 for x in v) for v in byg.values())/(len(Q)-len(byg))
k0 = (sum(sizes) - sum(s*s for s in sizes)/sum(sizes))/(len(byg)-1)
icc = (msb - msw)/(msb + (k0-1)*msw)
deff = 1 + (k0 - 1)*icc
P("| quantity | value |")
P("|---|---|")
P("| base over-hit rate | %.4f |" % grand)
P("| mean quotes per game (k0) | %.1f |" % k0)
P("| ICC of `over won` within game | **%.4f** |" % icc)
P("| design effect 1+(k0-1)*ICC | **%.2f** |" % deff)
P("| n quotes | %s |" % format(len(Q), ","))
P("| **n_eff** | **%.0f** |" % (len(Q)/deff))
P("")
# game-block bootstrap on the over rate for a sanity check
gl = list(byg.values())
bs = []
for _ in range(4000):
    s = 0; c = 0
    for _ in range(len(gl)):
        g = random.choice(gl); s += sum(x["over"] for x in g); c += len(g)
    bs.append(s/c)
bs.sort()
naive_se = math.sqrt(grand*(1-grand)/len(Q))
P("Game-block bootstrap of the base over rate: %.4f, 95%% CI [%.4f, %.4f], SE %.4f."
  % (grand, bs[100], bs[-100], statistics.pstdev(bs)))
P("Naive iid SE would be %.4f. Ratio %.2f, so the design effect measured directly is **%.2fx** --"
  % (naive_se, statistics.pstdev(bs)/naive_se, (statistics.pstdev(bs)/naive_se)**2))
P("consistent with the ICC estimate above.")
P("")
P("Practical reading: the prop book's %s quotes carry roughly **%.0f independent quotes** of"
  % (format(len(Q), ","), len(Q)/deff))
P("information. That is a far milder deflation than the in-play feed (45-60x) -- pre-game props")
P("across different players really are mostly independent -- but it is not 1.0, and a study that")
P("quotes an unadjusted t-stat on %s is overstating its precision by about %.0f%%."
  % (format(len(Q), ","), 100*(math.sqrt(deff)-1)))
P("")

# ---------- horizon ----------
ovp = [1.0/r["oo"] for r in Q]; unp = [1.0/r["uo"] for r in Q]
mg = [ovp[i] + unp[i] - 1.0 for i in range(len(Q))]
roi_o = statistics.mean((r["oo"]-1.0) if r["over"] else -1.0 for r in Q)
roi_u = statistics.mean((r["uo"]-1.0) if not r["over"] else -1.0 for r in Q)
P("### Book margin on the surviving two-sided quotes (methodology law 4)")
P("")
P("| quantity | value |")
P("|---|---|")
P("| median two-sided overround | **%.2f%%** |" % (100*statistics.median(mg)))
P("| mean overround | %.2f%% |" % (100*statistics.mean(mg)))
P("| p10 / p90 overround | %.2f%% / %.2f%% |" % (100*sorted(mg)[len(mg)//10], 100*sorted(mg)[9*len(mg)//10]))
P("| median breakeven hit rate needed on the Over (1/odds) | **%.2f%%** |" % (100*statistics.median(ovp)))
P("| median breakeven hit rate needed on the Under | %.2f%% |" % (100*statistics.median(unp)))
P("| observed base Over hit rate | %.2f%% |" % (100*grand))
P("| flat-bet ROI, blind Over on every quote | **%+.2f%%** |" % (100*roi_o))
P("| flat-bet ROI, blind Under on every quote | **%+.2f%%** |" % (100*roi_u))
P("")
P("The board carries a median **%.1f%%** overround, so an Over needs about **%.1f%%** to break even"
  % (100*statistics.median(mg), 100*statistics.median(ovp)))
P("and it actually lands **%.1f%%**. That %.1f-point shortfall is the house edge, and it is the"
  % (100*grand, 100*(statistics.median(ovp)-grand)))
P("hurdle any claimed signal must clear -- **not 50%**. Blind flat betting confirms it: every Over")
P("on the board returns **%+.1f%%** and every Under **%+.1f%%**, i.e. both sides lose roughly the vig."
  % (100*roi_o, 100*roi_u))
P("")
P("Two things follow. First, the base Over rate is **%.2f%%** -- the board is neither systematically"
  % (100*grand))
P("over-lined nor under-lined, so there is no always-over base-rate artifact to be fooled by")
P("(methodology law 9). Second, the two sides are close to symmetric in cost, so a finding that")
P("appears only on one side and not as its mirror on the other is a red flag, not a discovery.")
P("")
P("## 4. The one-month-horizon limitation, with numbers")
P("")
bt = [t for t in (ts(r.get("captured_utc")) for r in BD) if t]
P("| horizon fact | value |")
P("|---|---|")
P("| prop-book capture window | %s .. %s (**%d days**) |" % (min(bt).date(), max(bt).date(), (max(bt).date()-min(bt).date()).days+1))
P("| in-play capture window | 2026-07-16 .. 2026-08-11 (**27 days**) |")
P("| 2026 games played league-wide in the whole file | %d |" % len(played))
P("| games with at least one gradable prop quote | **%d** (%.0f%% of played) |" % (len(byg), 100*len(byg)/len(played)))
P("| games with in-play odds | **27** (%.0f%% of played) |" % (100*27/len(played)))
P("| distinct players with a gradable quote | %d |" % len(set(r["pl"] for r in Q)))
P("| Model S live forward record | 21-27 settled bets |")
P("")
P("What one month buys you, in effect size. Using the measured design effect above, the minimum")
P("ROI detectable at 80% power and alpha=0.05, two-sided, on flat 1u bets priced around 1.87:")
P("")
sd_ret = 0.97
for n in [50, 100, 200, 500, 1000, 2000, len(Q)]:
    ne = n/deff
    mde = 2.80 * sd_ret / math.sqrt(ne)
    P("- n=%s bets (n_eff %.0f) -> smallest reliably detectable edge **%+.1f%% ROI**" % (format(n, ","), ne, 100*mde))
P("")
def mde(n): return 100 * 2.80 * sd_ret / math.sqrt(n / deff)
P("So a full month of the entire board -- every player, every market, both sides -- can just about")
P("resolve a **%+.1f%%** edge. The strategies this project actually runs bet a few times a night:" % mde(len(Q)))
P("at n=100 bets nothing below **%+.0f%% ROI** is distinguishable from noise, and at n=21 (the live" % mde(100))
P("Model S record) the detectable floor is around **%+.0f%% ROI**. A live +6.8%% on 21 bets is" % mde(21))
P("therefore consistent with anything from a large edge to a large *negative* one, and is not")
P("evidence of either. This is the single most important number in this audit: **the dataset's")
P("horizon, not the analyst's cleverness, is what caps what can be concluded.**")
P("")
P("Three further horizon constraints that no amount of within-window analysis can relieve:")
P("")
P("1. **One season, no cross-season replication.** Everything gradable is 2026. `elo_model/` holds")
P("   2019-2025 box and play-by-play, but it carries **no odds for those seasons that match this")
P("   book**, so a signal found here cannot be re-tested on an earlier year.")
P("2. **One slice of one season.** The window is late June to late August: mid-season through the")
P("   run-in. No opening-weeks period (when books are least calibrated and lines move most) and no")
P("   playoffs. Any seasonality is entirely unobserved.")
P("3. **The book is one book.** 1xbet for props, Pinnacle for game markets. A price artifact")
P("   specific to 1xbet's prop pricing is indistinguishable from a real market inefficiency, because")
P("   there is no second prop book to disagree with it -- other than Pinnacle's %d prop rows, which"
  % len(L("pinn_snapshots.csv")))
P("   is exactly the comparison the project's live 'sharp gap' signal already exploits.")
P("")
