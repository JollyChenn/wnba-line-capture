for r in cur:
    kk[((r.get("player") or "").lower(), r.get("market"), r.get("side"), f(r.get("line")), r.get("captured_utc"))].add(f(r.get("odds")))
contra = sum(1 for v in kk.values() if len(v) > 1)
P("")
P("### 1a. Observation-level exclusion ledger -- prop book")
P("")
P("| # | reason | rows dropped |")
P("|---|---|---|")
